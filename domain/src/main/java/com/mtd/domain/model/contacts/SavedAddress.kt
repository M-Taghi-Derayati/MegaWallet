package com.mtd.domain.model.contacts

/**
 * یک آدرسِ ثبت‌شده در دفترِ آدرس‌ها.
 *
 * ⚠️ [address] هرگز نرمال‌سازی نمی‌شود — نه کوچک می‌شود و نه trim فراتر از فاصله‌های ابتدا و انتها.
 * base58 ترون به حروف حساس است و یک آدرسِ کوچک‌شده روی آن زنجیره اصلاً آدرس نیست. یکتایی هم با
 * [id] سنجیده می‌شود، نه با مقایسهٔ رشتهٔ آدرس.
 */
data class SavedAddress(
    val id: String,
    val name: String,
    val address: String,
    /**
     * شبکه‌ای که این آدرس برای آن ثبت شده. `null` یعنی «هر شبکه‌ای از همین خانواده» — کاربر
     * معمولاً یک آدرسِ EVM را برای همهٔ زنجیره‌های EVM می‌خواهد و مجبورکردنش به ثبتِ جداگانه
     * برای هر شبکه، دفترچه را به فهرستی از تکرار تبدیل می‌کند.
     */
    val networkId: String? = null,
    val createdAtMillis: Long = 0L
)
